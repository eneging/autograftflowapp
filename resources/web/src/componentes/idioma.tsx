import { createContext, useContext } from "react";
import { DEDOS, type Dedo, type Idioma, type Mano } from "../../../shared/plataforma";

/*
 * Idioma de la página del firmante (español o inglés). Los textos se escriben en español en el código y t() los
 * traduce con el diccionario EN; si una frase no está, se muestra en español. Fuera de la página del firmante el
 * idioma es siempre español (valor por defecto del contexto), así el resto de la plataforma no cambia.
 */
export const IdiomaContexto = createContext<Idioma>("es");
export const usarIdioma = () => useContext(IdiomaContexto);

type Vars = Record<string, string | number>;
const poner = (s: string, v?: Vars) => (v ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(v[k] ?? "")) : s);
export const traducir = (idioma: Idioma, es: string, v?: Vars) => poner(idioma === "en" ? EN[es] ?? es : es, v);
/** t("Texto en español", { variables }) en el idioma de la página. */
export function usarT() {
  const idioma = useContext(IdiomaContexto);
  return (es: string, v?: Vars) => traducir(idioma, es, v);
}

const DEDOS_EN: Record<Dedo, string> = { pulgar: "thumb", indice: "index finger", medio: "middle finger", anular: "ring finger", menique: "little finger" };
/** «Huella del dedo índice de la mano derecha» / «Right index finger print». */
export const textoDedoEn = (idioma: Idioma, d: { mano: Mano; dedo: Dedo }) => idioma === "en"
  ? `${d.mano === "derecha" ? "Right" : "Left"} ${DEDOS_EN[d.dedo]} print`
  : `Huella del dedo ${DEDOS[d.dedo].toLowerCase()} de la mano ${d.mano}`;
/** Nombre del dedo para el rótulo del campo de huella («Índice derecho» / «Right index finger»). */
export const rotuloDedo = (idioma: Idioma, d: { mano: Mano; dedo: Dedo }) => idioma === "en"
  ? `${d.mano === "derecha" ? "Right" : "Left"} ${DEDOS_EN[d.dedo]}`
  : `${DEDOS[d.dedo]} ${d.mano === "derecha" ? "derecho" : "izquierdo"}`;

